// Exercise 029: Stamina Reduction on Evasion
// Objective: Decrement stamina by 1 after a dodge action using --

// Initializing character stamina
let stamina = 100;

// Executing dodge and reducing stamina
console.log("Hero dodges the attack!");
stamina--;

// Outputting remaining stamina
console.log("Remaining Stamina: " + stamina);