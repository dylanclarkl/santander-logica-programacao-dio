// Exercise 04: Experience Points Tracking
// Objective: Simulate the accumulation of experience points (XP).

// Declaring current XP
let currentXp = 450;

// Declaring XP goal to level up
const xpGoalToLevelUp = 1000;

// Declaring remaining XP
let remainingXp = xpGoalToLevelUp - currentXp;

// Displaying in the console
console.log("Current XP: " + currentXp);
console.log("XP needed for next level: " + remainingXp);